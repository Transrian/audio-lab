NAME = "peertube-edu-captions-fr"
LANGUAGE = "fr"
# The listing the train set reads: the captions set is a selection of its talks,
# so it reads the same pinned file and never the catalogue.
LISTING_PATH = Path(__file__).parent / "peertube_edu_listing.json"

# The training set this one is cut out of, by talk id (decision 0002).
TRAIN_NAME = "peertube-edu-fr-train"

# A clip is a run of merged cues: how long it must be, how long it may be, and
# how far a clip's cues may drift apart in time before it is two clips.
CLIP_MIN_SECONDS = 3.0
CLIP_MAX_SECONDS = 15.0
MAX_CUE_GAP_SECONDS = 1.0
# The share of a talk, in clips: the clips of one recording are not independent,
# and a panel resamples them together.
MAX_CLIPS_PER_TALK = 40
# The WER gate: a clip whose caption is more wrong than this against Whisper's
# transcription of the clip is out of sync with its audio, or condensed.
MAX_CLIP_WER = 0.35
# A set of fewer than this many talks would not span enough recordings to
# measure anything: the preparation stops and reports instead.
MIN_TALKS = 20

# The title words that make a talk a ``tech`` talk: the report of the reference
# runs shows the WER of the set's tech clips separately (plan 01, T7).
TECH_TITLE = re.compile(
    r"informatique|programm|python|algorithm|nsi|numérique|réseau|linux|donnée"
    r"|code|logiciel|web|intelligence artificielle|\bia\b|cyber|robot"
    r"|base de données|javascript|html|tableur",
    re.IGNORECASE,
)

# The VTT timestamp: ``MM:SS.mmm`` or ``HH:MM:SS.mmm``, the comma as well as
# the dot: both appear in files PeerTube has served.
CUE_TIMESTAMP = re.compile(r"^(?:(\d+):)?(\d{1,2}):(\d{2})[.,](\d{3})$")
# The markup a cue may hold (voice, style, position), dropped from the label.
CUE_TAG = re.compile(r"<[^>]*>")

# The source as the shared pipeline reads it: the train set's listing, the same
# audio, the same spread. The captions set's own fetcher is custom because its
# labels come from the captions, not from a labelling pass.
SOURCE = TalkSource(
    name=NAME,
    language=LANGUAGE,
    allowed_licenses=frozenset({"CC-BY", "CC0-1.0"}),
    listing_path=LISTING_PATH,
    listing_filter={
        "instances": list(peertube_edu.INSTANCES),
        "licence_ids": list(peertube_edu.FILTER.licence_ids),
        "language": peertube_edu.FILTER.language,
        "local": True,
        "min_duration_s": peertube_edu.MIN_TALK_SECONDS,
        "channel_words_left_out": list(peertube_edu.NON_SPEECH_WORDS),
        "title_words_left_out": list(peertube_edu.PERFORMANCE_WORDS),
        "captions": "the French track with automaticallyGenerated: false",
    },
    lister=peertube_edu.list_talks,
    audio_url=peertube.smallest_file_url,
    spread_by=peertube_edu.spread_key,
)


def captions_url(instance: str, talk_id: str) -> str:
    """The API's list of caption tracks of one video."""
    return f"{instance}/api/v1/videos/{talk_id}/captions"


def human_french_caption(rows: list[dict]) -> dict | None:
    """The video's French caption track written by a person, if it has one.

    ``automaticallyGenerated`` must be the boolean ``false``: a track the API
    does not mark is not a human track, and a track of another language is not
    a French reference.
    """
    for row in rows:
        generated = row.get("automaticallyGenerated")
        language = (row.get("language") or {}).get("id")
        if generated is False and language == "fr":
            return row
    return None


def scan_captions(
    http: httpx.Client, talks: list[Talk], cache: Path, *, verbose: bool = True
) -> dict[str, list[dict]]:
    """The list of caption tracks of every talk, one cached JSON file per video.

    The instances are read in parallel, one request at a time from each: that
    is the pace an instance answers, and a 429 from a faster client is what
    ``peertube.get_json`` retries. A talk whose list was already read is never
    asked again, so a stopped scan resumes where it was: a stop ends the threads
    at their next talk, and the run raises rather than report on a partial scan.
    """
    by_instance: dict[str, list[Talk]] = {}
    for talk in talks:
        by_instance.setdefault(talk.instance, []).append(talk)
    found: dict[str, list[dict]] = {}
    cache_dir = cache / "captions"
    cache_dir.mkdir(parents=True, exist_ok=True)
    before = set(cache_dir.glob("*.json"))

    def read_instance(instance: str, instance_talks: list[Talk]) -> None:
        for talk in instance_talks:
            if stop_requested():
                return
            path = cache_dir / f"{talk.id}.json"
            if path.is_file():
                data = json.loads(path.read_text(encoding="utf-8"))
            else:
                data = peertube.get_json(http, captions_url(instance, talk.id))
                pending = path.with_suffix(".pending")
                pending.write_text(json.dumps(data, ensure_ascii=False) + "\n", encoding="utf-8")
                pending.rename(path)
            found[talk.id] = data.get("data", [])

    with ThreadPoolExecutor(max_workers=max(len(by_instance), 1)) as pool:
        list(pool.map(lambda pair: read_instance(*pair), by_instance.items()))
    raise_if_stopped("captions scan stopped")
    if verbose:
        asked = len(set(cache_dir.glob("*.json")) - before)
        say(f"  {asked} caption lists asked, {len(talks) - asked} read from the cache")
    return found


def caption_url(caption: dict, instance: str) -> str:
    """Where one caption track's WebVTT file is served from."""
    return caption.get("fileUrl") or instance + caption["captionPath"]


def fetch_captions(
    http: httpx.Client, talk: Talk, caption: dict, cache: Path
) -> tuple[Path, list[Segment]]:
    """The cues of one talk's human French captions, the file cached by the talk.

    The file is small, so a request that the instance refuses is retried the way
    the API is (a 429, a busy 5xx), one request a second. Cues keep their text
    with the markup removed; a blank cue is no cue.
    """
    path = cache / "vtt" / f"{talk.id}.fr.vtt"
    if not path.is_file():
        _get_vtt(http, caption_url(caption, talk.instance), path)
    cues = parse_cues(path.read_text(encoding="utf-8"))
    return path, cues


def _get_vtt(http: httpx.Client, url: str, destination: Path) -> None:
    """One WebVTT file, retried as the API is, and landed under its final name whole."""
    for attempt in range(1, peertube.RETRIES + 1):
        raise_if_stopped(f"download of {destination.name} stopped")
        time.sleep(peertube.PAUSE_S)
        response = http.get(url)
        if response.status_code in peertube.RETRY_STATUSES:
            time.sleep(peertube.retry_after_s(response.headers.get("retry-after"), 5.0 * attempt))
            continue
        if response.status_code >= 400:
            raise DownloadError(f"{url}: HTTP {response.status_code}")
        destination.parent.mkdir(parents=True, exist_ok=True)
        pending = destination.with_suffix(".pending.vtt")
        pending.write_bytes(response.content)
        pending.rename(destination)
        return
    raise DownloadError(f"{url}: still refused after {peertube.RETRIES} attempts")


def _cue_seconds(hours: str | None, minutes: str, seconds: str, tenths: str) -> float:
    return int(hours or 0) * 3600 + int(minutes) * 60 + int(seconds) + int(tenths) / 1000


def parse_cues(vtt: str) -> list[Segment]:
    """The cues of a WebVTT file: both timestamp forms, tags dropped.

    A cue is a ``start --> end`` line and the non-blank lines that follow it,
    joined with a space. Everything else in the file — the header, identifiers,
    NOTE and STYLE blocks — is skipped, because a note is not a cue and its
    lines hold no arrow.
    """
    cues: list[Segment] = []
    lines = vtt.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i].strip()
        i += 1
        if "-->" not in line:
            continue
        arrow = line.split("-->")
        if len(arrow) != 2:
            continue
        start = CUE_TIMESTAMP.match(arrow[0].strip())
        end = CUE_TIMESTAMP.match(arrow[1].strip())
        if start is None or end is None:
            continue
        text_lines: list[str] = []
        while i < len(lines) and lines[i].strip():
            text_lines.append(lines[i].strip())
            i += 1
        text = CUE_TAG.sub("", " ".join(text_lines)).strip()
        if text:
            cues.append(
                Segment(
                    start_s=_cue_seconds(*start.groups()),
                    end_s=_cue_seconds(*end.groups()),
                    text=text,
                )
            )
    return cues


def clips_from_cues(cues: list[Segment]) -> tuple[list[Segment], Counter[str]]:
    """The clips the cues merge into, and what was left out, and why.

    A clip is a run of consecutive cues. A run ends on a pause of more than
    :data:`MAX_CUE_GAP_SECONDS` — a clip never spans a gap its cues would have
    to sit across — and it takes no cue that would push it past
    :data:`CLIP_MAX_SECONDS`. A run that is already at least
    :data:`CLIP_MIN_SECONDS` long ends where its last cue ends a sentence, so a
    clip ends on ``.`` ``?`` ``!`` or ``…`` when the cues allow it. What is left
    out: a run that never reaches the floor, and a single cue longer than the
    ceiling, which no merge can shorten.
    """
    clips: list[Segment] = []
    left_out: Counter[str] = Counter()
    run: list[Segment] = []

    def end_run() -> None:
        nonlocal run
        if not run:
            return
        start, end = run[0].start_s, run[-1].end_s
        if end - start < CLIP_MIN_SECONDS:
            left_out[f"a run of cues shorter than {CLIP_MIN_SECONDS:g} s"] += 1
        elif end - start > CLIP_MAX_SECONDS:
            left_out[f"a run of cues longer than {CLIP_MAX_SECONDS:g} s"] += 1
        else:
            clips.append(Segment(round(start, 2), round(end, 2), " ".join(cue.text for cue in run)))
        run = []

    for cue in cues:
        if not run:
            if cue.end_s - cue.start_s > CLIP_MAX_SECONDS:
                left_out[f"a cue longer than {CLIP_MAX_SECONDS:g} s"] += 1
                continue
            run = [cue]
            continue
        if (
            cue.start_s - run[-1].end_s > MAX_CUE_GAP_SECONDS
            or cue.end_s - run[0].start_s > CLIP_MAX_SECONDS
        ):
            end_run()
            if cue.end_s - cue.start_s > CLIP_MAX_SECONDS:
                left_out[f"a cue longer than {CLIP_MAX_SECONDS:g} s"] += 1
                continue
            run = [cue]
            continue
        run.append(cue)
        if cue.text.endswith(SENTENCE_ENDS) and run[-1].end_s - run[0].start_s >= CLIP_MIN_SECONDS:
            end_run()
    end_run()
    return clips, left_out


def category_of(title: str) -> str:
    """``tech`` when the talk's title names a technical subject, else ``general``."""
    return "tech" if TECH_TITLE.search(title) else "general"


def scan_report(
    talks: list[Talk], found: dict[str, list[dict]]
) -> tuple[list[tuple[Talk, dict]], Counter, Counter]:
    """The talks that hold a human French caption, and what the scan found.

    Returns the usable talks with the caption row they came from, the count of
    caption tracks the scan saw (by kind: human or generated), and the count of
    usable talks per instance.
    """
    usable: list[tuple[Talk, dict]] = []
    tracks: Counter[str] = Counter()
    per_instance: Counter[str] = Counter()
    for talk in talks:
        rows = found.get(talk.id, [])
        for row in rows:
            tracks["generated" if row.get("automaticallyGenerated") else "human"] += 1
        caption = human_french_caption(rows)
        if caption is not None:
            usable.append((talk, caption))
            per_instance[talk.instance] += 1
    return usable, tracks, per_instance


def wer_deciles(wers: list[float]) -> str:
    """The deciles of a list of WERs, one line for a report."""
    if not wers:
        return "no WER"
    ordered = sorted(wers)
    deciles = []
    for decile in range(10):
        index = min(len(ordered) - 1, (decile * len(ordered)) // 10)
        deciles.append(f"{ordered[index]:.2f}")
    return "deciles " + " ".join(deciles)


def fetch_peertube_edu_captions_fr(
    name: str, cache_dir: Path, dataset_dir: Path, *, verbose: bool = True
) -> int:
    """Prepare the set: the human-captioned talks of the listing, cut and checked.

    The scan of the caption lists is cached per video, so the run may be
    stopped after it and resumed; the talks already read from the cache are not
    asked again. The set is a selection of the train set's listing, so it
    leaves the train set's talks out before it asks anything else for them.
    """
    listed_on, talks = read_listing(SOURCE)
    cache = cache_dir / NAME
    cache.mkdir(parents=True, exist_ok=True)
    with http_client() as http:
        found = scan_captions(http, talks, cache, verbose=verbose)
    usable, tracks, per_instance = scan_report(talks, found)
    if verbose:
        hours = sum(talk.duration_s for talk, _ in usable) / 3600
        say(
            f"  listing of {listed_on}: {len(talks)} talks; the scan saw "
            f"{tracks['human']} human and {tracks['generated']} generated caption tracks"
        )
        per_instance_report = ", ".join(
            f"{count} of {instance.removeprefix('https://').split('.')[0]}"
            for instance, count in sorted(per_instance.items())
        )
        say(
            f"  {len(usable)} talks with human French captions, "
            f"{hours:.1f} h: {per_instance_report}"
        )
    if len(usable) < MIN_TALKS:
        raise DownloadError(
            f"only {len(usable)} talks of the {len(talks)} listed hold a human French "
            f"caption; a set of fewer than {MIN_TALKS} talks cannot measure anything, "
            "and the preparation stops (plan 01, T7)"
        )
    # The train set's talks are out: a clip of a talk may not measure a model
    # that was trained on it (decision 0002).
    used = evaluation_groups(TRAIN_NAME, root=dataset_dir.parent)
    kept_talks = [(talk, caption) for talk, caption in usable if talk.id not in used]
    left_to_train = len(usable) - len(kept_talks)
    if verbose:
        say(
            f"  {left_to_train} of the {len(usable)} usable talks "
            f"are in {TRAIN_NAME} and are left out"
        )
    order = reading_order([talk for talk, _ in kept_talks], SEED, SOURCE.spread_by)
    caption_of = {talk.id: caption for talk, caption in kept_talks}
    with (
        ManifestBuilder(
            dataset_dir,
            verbose=verbose,
            total=MAX_CLIPS_PER_TALK * max(1, len(order)),
        ) as builder,
        http_client() as http,
        client(SEGMENT_MODEL) as whisper_client,
    ):
        whisper = served(whisper_client, LANGUAGE).one_pass()
        take = Take(
            name=name,
            builder=builder,
            language=LANGUAGE,
            source_split="listing (human captions)",
            license="CC-BY or CC0-1.0, per talk",
            text_has_casing_punct=True,
            group_kind="recording",
            cap=MAX_CLIPS_PER_TALK * max(1, len(order)),
            cap_per_group=MAX_CLIPS_PER_TALK,
        )
        tally: Counter[str] = Counter()
        wers: list[tuple[str, float]] = []
        for position, talk in enumerate(order, start=1):
            audio_path = audio_file(http, cache, SOURCE, talk)
            if audio_path is None:
                tally["talks whose audio could not be read"] += 1
                continue
            audio = load_audio(audio_path)
            _, cues = fetch_captions(http, talk, caption_of[talk.id], cache)
            segments, left_out = clips_from_cues(cues)
            for reason, count in left_out.items():
                tally[f"cues left out: {reason}"] += count
            if not segments:
                tally["talks whose captions hold no clip"] += 1
                continue
            answers = Answers(cache / clips_file(talk, SEGMENT_MODEL))

            def hear(segment: Segment, answers=answers, audio=audio) -> str | None:
                try:
                    return clip_text(answers, segment, audio, whisper.transcribe)
                except TranscriptionError:
                    return None

            heard = map_requests(hear, segments, whisper.concurrency)
            raise_if_stopped("labelling stopped")
            for segment, text in zip(segments, heard, strict=True):
                if text is None:
                    tally["clips Whisper failed on"] += 1
                    continue
                wer = round(counts(segment.text, text, LANGUAGE, "normalized").wer, 4)
                wers.append((f"{talk.id}-{round(segment.start_s * 100):07d}", wer))
                if wer > MAX_CLIP_WER:
                    tally["clips the caption and Whisper do not agree on"] += 1
                    continue
                take.offer(
                    f"{talk.id}-{round(segment.start_s * 100):07d}",
                    cut(audio, segment),
                    text=segment.text,
                    group=talk.id,
                    license=talk.license,
                    source_url=talk.url,
                    source_title=talk.title,
                    source_author=talk.author,
                    category=category_of(talk.title),
                )
            if verbose:
                say(f"  ... {position} of {len(order)} usable talks read")
        if verbose:
            values = [wer for _, wer in wers]
            under = sum(1 for wer in values if wer <= MAX_CLIP_WER)
            say(
                f"  {wer_deciles(values)}; "
                f"{under} of {len(values)} clips at or under {MAX_CLIP_WER}"
            )
            others = [f"{count} {reason}" for reason, count in sorted(tally.items())]
            if others:
                say(f"  also {', '.join(others)}")
            say(f"  {take.report()}")
        builder.write()
        (cache / "alignment-wers.json").write_text(
            json.dumps(
                {"threshold": MAX_CLIP_WER, "wers": sorted(wers, key=lambda row: row[1])},
                ensure_ascii=False,
            )
            + "\n",
            encoding="utf-8",
        )
    return take.kept
