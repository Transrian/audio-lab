"""The education ministry's human captions (``peertube-edu-captions-fr``).

The ministry's PeerTube instances (see :mod:`audiolab.data.peertube_edu`)
publish captions with their videos. Most are generated by PeerTube's own
speech model (``automaticallyGenerated: true``), but some were written by the
person who recorded the video and uploaded by hand
(``automaticallyGenerated: false``). Only the human ones may be references: a
machine caption is another model's output, and scoring a model against
another model's output would measure nothing about the model under test.

The caption text is the label, and the clips are cut at the cues' own time
codes — no labelling model is in the loop at all. One model is asked one
question, and it is Whisper's: is the caption of each cut clip in sync with
the audio it covers? It transcribes the clip, and the clip is kept only when
the word error rate of its caption against the transcription, in the
normalized view, is at most :data:`MAX_CLIP_WER`. That gate is what removes
condensed subtitles and cues misplaced on the timeline, and it is also what
biases the set toward the clips Whisper gets right: a clip Whisper mishears
badly enough to fail the gate never reaches the set, whatever a model under
test would have made of it. The card states the bias plainly.

The set reads the same pinned listing as
``peertube-edu-fr-train`` and leaves its talks out (decision 0002): a talk is
one recording, and a clip of it cannot measure a model that was trained on it.
The train fetcher keeps the check the other way: it reads this set's manifest
through ``evaluation_groups`` and skips the talks it holds.
"""

